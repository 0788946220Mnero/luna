def project_context_message(analysis_text: str) -> str:
    return f"سياق المشروع الحالي:\n{analysis_text}"


def build_system_prompt(skills_catalog: str = "", strict_validation: bool = False) -> str:
    """يبني التوجيه مع قائمة المهارات المتاحة في مساحة العمل الحالية."""
    parts = [SYSTEM_PROMPT]
    if skills_catalog:
        parts.append("## المهارات\n\n" + skills_catalog)
    if strict_validation:
        parts.append(
            "## تنبيه\n\nالتحقق الصارم مفعّل: أي ملف لا يجتاز الفحص **لن يُحفظ**. "
            "راجع الصيغة قبل الإرسال."
        )
    return "\n\n".join(parts)
